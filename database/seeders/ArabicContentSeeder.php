    /** "Departs 20:00" → "المغادرة 20:00", "Full day" → "يوم كامل"; time ranges stay as they are. */
    public static function timeLabel(?string $label): ?string
    {
        if ($label === null) {
            return null;
        }

        return str_replace(['Departs', 'Arrives', 'Full day'], ['المغادرة', 'الوصول', 'يوم كامل'], $label);
    }

