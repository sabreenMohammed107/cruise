    /** Write each value only where the column is still empty. */
    private function fill(?Model $model, array $values): void
    {
        if (! $model) {
            return;
        }
        foreach ($values as $column => $value) {
            if (blank($model->getAttribute($column))) {
                $model->setAttribute($column, $value);
            }
        }
        $model->save();
    }

